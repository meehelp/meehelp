/**
 * npm run evidence — writes docs/seo/CONTENT-EVIDENCE.json and CONTENT-EVIDENCE.md
 * from src/data/evidence.ts and src/data/product-facts.ts.
 * `npm test` fails if the committed files are out of date.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { evidence, openQuestions, serviceModelEvidence } from "@/data/evidence";
import { productFacts } from "@/data/product-facts";

const usedBy = (id: string) => productFacts.filter((f) => f.evidence.includes(id)).map((f) => f.id);

const json = {
  note: "Evidence ledger for Website V2 product claims. Sources were read read-only; no secrets or personal records were used.",
  generatedFrom: "src/data/evidence.ts",
  items: evidence.map((e) => ({ ...e, productFacts: usedBy(e.id) })),
  serviceModelEvidence,
  openQuestions,
};

const cell = (s: string) => s.replaceAll("|", "\\|").replaceAll("\n", " ");
const rows = evidence.map(
  (e) =>
    `| \`${e.id}\` | ${cell(e.claim)} | ${e.proposition}${e.services && e.services.length < 5 ? ` (${e.services.join(", ")})` : ""} | ${e.sourceRepository} — \`${cell(e.sourceFile)}\`${e.sourceLines ? ` ${e.sourceLines}` : ""} | ${e.confidence} | ${e.publicSafe ? "yes" : "**no**"} | ${e.requiresBusinessApproval ? "yes" : "no"} | ${e.usedOnSite ? "yes" : "—"} |`,
);
const notes = evidence.filter((e) => e.note).map((e) => `- \`${e.id}\`: ${e.note}`);
const md = `# Content evidence ledger

Generated by \`npm run evidence\` from \`src/data/evidence.ts\` — edit that file, not this one.

This tells future sessions **which product facts are grounded in code and which are assumptions**.
Sources were read **read-only** (Phase 4.5) from MeeHelp_User_App, MeeHelp_Helper_App, MeeHelp_Backend, meehelp-admin
and the 2022 legacy apps. Only source code and customer-visible app copy were used — no database records, personal
data or credentials. Most catalogue values (category/task names, prices, plan sets, cities) live in the production
database and are **not** known from code.

## How to use it

- Website copy may state an app mechanic only through \`src/data/product-facts.ts\`, citing items below.
- \`publicSafe: no\` items are internal (tuning values, negative findings used as guards) and must never be published.
- \`requiresBusinessApproval: yes\` items are grounded in code but still need sign-off before a page using them goes live.
- Confidence: **high** = exact string or hardcoded value seen; **medium** = inferred (e.g. task names from icon IDs) or
  partly server-driven; **low** = weak signal.

## Ledger (${evidence.length} items, ${evidence.filter((e) => e.usedOnSite).length} used on the site)

| id | claim | proposition | source | confidence | public | approval | on site |
|---|---|---|---|---|---|---|---|
${rows.join("\n")}

## Notes and caveats

${notes.join("\n")}

## Implementation vs business confirmation

| Service | Marketplace evidence | On-demand evidence |
|---|---|---|
${Object.entries(serviceModelEvidence)
  .map(([s, m]) => `| ${s} | ${m.marketplace.length ? m.marketplace.map((x) => `\`${x}\``).join(", ") : "**none in code** (business confirmation only)"} | ${m.onDemand.map((x) => `\`${x}\``).join(", ")} |`)
  .join("\n")}

- **Instant booking**: the business confirmed instant, scheduled and hourly booking for all five categories. In the
  current app, "Book now" exists for one-time cleaning; hourly bookings (cooking, baby care, elder care, patient care)
  are scheduled at least 2 hours ahead and up to 5 days ahead. Website copy follows the app (\`bookNow\` in
  \`src/data/on-demand.ts\`) until the business says otherwise.
- **Elder care vs patient care**: both exist as separate hourly-booking tasks (icon IDs 38 and 39). On the marketplace
  side, helpers register under "Maid/Cook/Patient Care/Baby Care" — there is no elder-care helper category.
  Task contents for both are configured on the server and were not visible.
- **On-demand prices and cancellation**: server-configured and inconsistent between code paths; left unknown.

## Open questions for the business

${openQuestions.map((q) => `- **${q.id}** — ${q.question} _Affects: ${q.affects}._`).join("\n")}
`;

mkdirSync("docs/seo", { recursive: true });
writeFileSync("docs/seo/CONTENT-EVIDENCE.json", JSON.stringify(json, null, 2) + "\n");
writeFileSync("docs/seo/CONTENT-EVIDENCE.md", md);
console.log(`docs/seo/CONTENT-EVIDENCE.json/.md: ${evidence.length} items, ${openQuestions.length} open questions`);
